import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

// The manager bundle needs literal colors — var(--sl-*) fails SB's color
// parser — so theme.values.ts is regenerated from the theme source on
// every storybook start.
export function syncThemeValues(): Record<string, string> {
  const dir = dirname(fileURLToPath(import.meta.url));
  const req = createRequire(import.meta.url);
  const themeCss = readFileSync(req.resolve("@sakulime-ui/theme/sakulime.css"), "utf8");

  const tokens = Object.fromEntries(
    [...themeCss.matchAll(/--sl-([\w-]+):\s*(#[0-9a-f]+)/gi)]
      .map(([, k, v]) => [k, v.toLowerCase()]),
  ) as Record<string, string>;

  // color-mix() tones from the theme → composite over --sl-bg
  const rgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const blend = (a: string, p: number) =>
    "#" + rgb(a).map((c, i) => Math.round(c * p + rgb(tokens.bg)[i] * (1 - p)).toString(16).padStart(2, "0")).join("");
  for (const [, name, src, pct] of themeCss.matchAll(
    /--sl-([\w-]+):\s*color-mix\(in srgb, var\(--sl-([\w-]+)\) (\d+)%/g,
  )) {
    tokens[name] = blend(tokens[src], Number(pct) / 100);
  }

  writeFileSync(
    resolve(dir, "theme.values.ts"),
    `// Generated by gen-theme-values.ts — do not edit.\nexport default ${JSON.stringify(tokens, null, 2)} as const;\n`,
  );
  return tokens;
}
