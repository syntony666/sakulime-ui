import type { StorybookConfig } from '@storybook/html-vite';
import remarkGfm from "remark-gfm";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// The manager bundle needs literal colors — var(--sl-*) fails SB's color
// parser — so theme.values.ts is regenerated from the theme source on
// every storybook start.
const dir = dirname(fileURLToPath(import.meta.url));
const themeCss = readFileSync(resolve(dir, "../../packages/shared/theme/sakulime.css"), "utf8");

const tokens = Object.fromEntries(
  [...themeCss.matchAll(/--sl-([\w-]+):\s*(#[0-9a-f]+)/gi)]
    .map(([, k, v]) => [k, v.toLowerCase()]),
) as Record<string, string>;

// color-mix() tones from the theme → composite over --sl-bg
const rgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const blend = (a: string, p: number) =>
  "#" + rgb(a).map((c, i) => Math.round(c * p + rgb(tokens.bg)[i] * (1 - p)).toString(16).padStart(2, "0")).join("");
for (const [, name, src, pct] of themeCss.matchAll(
  /--sl-([\w-]+):\s*color-mix\(in srgb, var\(--sl-([\w-]+)\) (\d+)%/g,
)) {
  tokens[name] = blend(tokens[src], Number(pct) / 100);
}

writeFileSync(
  resolve(dir, "theme.values.ts"),
  `// Generated by main.ts — do not edit.\nexport default ${JSON.stringify(tokens, null, 2)} as const;\n`,
);

const config: StorybookConfig = {
  stories: ["../src/**/*.stories.@(js|ts)", "../src/**/*.mdx"],
  addons: [
    {
      name: "@storybook/addon-docs",
      options: {
        mdxPluginOptions: {
          mdxCompileOptions: {
            // GFM tables etc. — not part of CommonMark
            remarkPlugins: [remarkGfm],
          },
        },
      },
    },
  ],
  framework: "@storybook/html-vite",
  staticDirs: ["../public"],
  managerHead: (head) => `${head}
    <title>Sakulime UI</title>
    <link rel="icon" type="image/svg+xml" href="./favicon.svg" />
    <style>
      /* table headers default to textColor like the sidebar — mute them to
         --sl-text-muted so they read as column labels, not nav text */
      .docblock-argstable-head th { color: ${tokens["text-muted"]}; }
    </style>`,
};
export default config;
